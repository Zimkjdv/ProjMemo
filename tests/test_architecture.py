def http_contract(application):
    schema = application.openapi()
    contract = []
    for path, operations in sorted(schema["paths"].items()):
        for method, operation in sorted(operations.items()):
            item = {
                "path": path, "method": method, "operationId": operation["operationId"],
                "parameters": operation.get("parameters", []), "responses": operation["responses"],
            }
            if "requestBody" in operation:
                request_body = json.loads(json.dumps(operation["requestBody"]))
                for media in request_body["content"].values():
                    reference = media["schema"].get("$ref")
                    if reference:
                        media["schema"] = schema["components"]["schemas"][reference.rsplit("/", 1)[1]]
                item["requestBody"] = request_body
            contract.append(item)
    return contract


def test_pre_refactor_paths_methods_fields_defaults_and_response_contract_are_unchanged():
    # Captured from 45369b5, before changing main.py; not regenerated by tests.
    expected = json.loads((ROOT / "tests/fixtures/http_contract.json").read_text(encoding="utf-8"))
    actual = http_contract(app)
    lifecycle_paths = {"/projects/{project_id}/manage": "get",
                       "/projects/{project_id}/lifecycle/{action}": "post"}
    backup_paths = {f"/settings/backup/{suffix}": "post" for suffix in (
        "preview", "preview/cancel", "restore/confirm", "retention", "cleanup/preview", "cleanup/confirm")}
    editor_paths = {"/editor": "get", "/editor/preview": "post"}
    rotation_paths = {"/settings/vault/change-password": "post"}
    export_paths = {"/projects/{project_id}/export"}
    new_paths = set(lifecycle_paths) | set(backup_paths) | set(editor_paths) | export_paths | set(rotation_paths)
    assert [item for item in actual if item["path"] not in new_paths] == expected
    assert {(item["path"], item["method"]) for item in actual if item["path"] in lifecycle_paths} == set(lifecycle_paths.items())
    routes = [route for route in app.routes if hasattr(route, "dependant")]
    probes = [route for route in routes if route.path in {"/health/live", "/health/ready"}]
    assert len(probes) == 2
    assert all(route.methods == {"GET"} and not route.include_in_schema for route in probes)
    assert {(item["path"], item["method"]) for item in actual if item["path"] in backup_paths} == set(backup_paths.items())
    assert {(item["path"], item["method"]) for item in actual if item["path"] in editor_paths} == set(editor_paths.items())
    assert {(item["path"], item["method"]) for item in actual if item["path"] in export_paths} == {
        ("/projects/{project_id}/export", "get"), ("/projects/{project_id}/export", "post")}
    assert len(routes) - len(probes) == len(expected) + len(new_paths) + 1
    assert {(item["path"], item["method"]) for item in actual if item["path"] in rotation_paths} == set(rotation_paths.items())
    assert len({(route.path, tuple(sorted(route.methods))) for route in routes}) == len(routes)
    assert all(any(dependency.call.__name__ == "require_csrf" for dependency in route.dependant.dependencies)
               for route in routes)


def test_routers_have_no_sql_and_services_do_not_import_http_or_main():
    for path in (ROOT / "app/routers").glob("*.py"):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        assert not any(isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                       and node.func.attr in {"execute", "executemany", "executescript", "commit", "rollback"}
                       for node in ast.walk(tree)), path.name
    for path in (ROOT / "app/services").glob("*.py"):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom):
                assert not (node.module or "").startswith(("fastapi", "starlette")), path.name
                assert node.module != "main", path.name
    main = ast.parse((ROOT / "app/main.py").read_text(encoding="utf-8"))
    assert not any(isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                   and node.func.attr in {"execute", "executemany", "executescript"} for node in ast.walk(main))


