def test_application_factory_has_independent_sessions_limiters_and_no_database_side_effect(tmp_path, monkeypatch):
    path = tmp_path / "must-not-exist.db"
    monkeypatch.setenv("PROJMEMO_DB_PATH", str(path))
    first = create_app(AppRuntime(unlock_attempt_limiter=UnlockAttemptLimiter(max_attempts=1)))
    second = create_app()
    assert not path.exists()
    one, two = first.state.runtime, second.state.runtime
    token = one.vault_sessions.issue(b"x" * 32)
    assert two.vault_sessions.get_key(token) is None
    one.unlock_attempt_limiter.record_failure()
    with pytest.raises(VaultRateLimited):
        one.unlock_attempt_limiter.check_allowed()
    two.unlock_attempt_limiter.check_allowed()
    assert one is not two and one is not app.state.runtime


