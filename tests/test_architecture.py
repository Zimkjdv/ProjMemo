def test_shared_export_projection_is_complete_and_regular_exports_never_decrypt(database, monkeypatch):
    runtime = AppRuntime()
    key = vault.setup(runtime, "test-only-master-password", "test-only-master-password")
    token = vault.issue_session(runtime, key, None)
    accounts.add_access_account(runtime=runtime, token=token, project_id=1, label="Encrypted", secret_value="must-not-export")
    with closing(sqlite3.connect(database)) as connection, connection:
        connection.executemany("INSERT INTO notes (project_id, title, content_markdown) VALUES (1, ?, 'Full text')",
                               [(f"Note-{number:03}",) for number in range(250)])
    data = projects.load_project_data(1)
    assert isinstance(data, ProjectData)
    assert len(data.notes) == 251
    assert list(data.template_context()) == [field.name for field in fields(ProjectData)]
    assert all(not {"secret_ciphertext", "secret_nonce", "secret_value"} & row.keys() for row in data.access_accounts)
    def never_decrypt(*args):
        pytest.fail("Regular exports must not decrypt, even when the vault is unlocked")
    monkeypatch.setattr(exports, "decrypt_secret", never_decrypt)
    captured = []
    def pdf(*args):
        captured.append(args)
        return b"%PDF-1.4\nservice fixture"
    monkeypatch.setattr(exports, "generate_project_pdf", pdf)
    assert "Note-000" in exports.export_project(1, "markdown").content
    document = exports.export_project(1, "pdf")
    assert document.content.startswith(b"%PDF-")
    assert len(captured[0][2]) == 251
    assert "must-not-export" not in str(captured)
    assert all(not {"secret_ciphertext", "secret_nonce", "secret_value"} & row.keys() for row in captured[0][5])


@pytest.mark.parametrize("language,expected", [("zh-Hant", "找不到此專案"), ("en", "Project not found")])
def test_domain_errors_stay_localized_at_http_boundary(database, language, expected):
    with pytest.raises(ApplicationError) as result:
        projects.load_project(999)
    assert result.value.status_code == 404
    with TestClient(create_app()) as client:
        client.cookies.set("projmemo_language", language)
        response = client.get("/projects/999")
        assert response.status_code == 404
        assert response.json() == {"detail": expected}
        assert "no-store" in response.headers["cache-control"]
