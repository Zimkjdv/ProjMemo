def test_account_encryption_failure_rolls_back_metadata_and_parent_time(database, monkeypatch):
    runtime = AppRuntime()
    key = vault.setup(runtime, "test-only-master-password", "test-only-master-password")
    token = vault.issue_session(runtime, key, None)
    before = dump(database)
    def fail_encryption(*args):
        raise RuntimeError("test-only crypto failure")
    monkeypatch.setattr(accounts, "encrypt_secret", fail_encryption)
