def dump(path):
    with closing(sqlite3.connect(path)) as connection:
        return tuple(connection.iterdump())


@pytest.mark.parametrize("operation,values", MUTATIONS, ids=[op.__name__ for op, _ in MUTATIONS])
def test_content_mutation_and_project_timestamp_are_one_transaction(database, monkeypatch, operation, values):
    module = accounts if operation.__module__.endswith("accounts") else content
    original = module.touch_project
    def fail_after_timestamp(connection, project_id):
        original(connection, project_id)
        raise sqlite3.OperationalError("test-only timestamp failure")
    monkeypatch.setattr(module, "touch_project", fail_after_timestamp)
    before = dump(database)
    with pytest.raises(sqlite3.OperationalError):
        operation(**values)
    assert dump(database) == before


